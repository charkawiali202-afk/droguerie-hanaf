const DICT: Record<Lang, Record<Key, string>> = { fr, en, ar };

const listeners = new Set<() => void>();
const read = (): Lang => {
  try { const v = localStorage.getItem(KEY); if (v === "ar" || v === "en") return v; } catch {}
  return "fr";
};
export function setLang(l: Lang) {
  try { localStorage.setItem(KEY, l); } catch {}
  document.documentElement.lang = l;
  document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
  listeners.forEach((f) => f());
}
const subscribe = (cb: () => void) => { listeners.add(cb); return () => listeners.delete(cb); };

export function useLang() {
  const lang = useSyncExternalStore(subscribe, read, () => "fr" as Lang);
  const t = (k: Key, vars?: Record<string, string | number>) =>
    DICT[lang][k].replace(/\{(\w+)\}/g, (_, v) => String(vars?.[v] ?? ""));
  return { lang, t };
}

export const catName = (t: ReturnType<typeof useLang>["t"], c: { id: string; name: string }) =>
  `cat.${c.id}` in fr ? t(`cat.${c.id}` as Key) : c.name;
export const catBlurb = (t: ReturnType<typeof useLang>["t"], c: { id: string; blurb?: string }) =>
  `catb.${c.id}` in fr ? t(`catb.${c.id}` as Key) : c.blurb ?? "";
